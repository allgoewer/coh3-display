//! Writes `src/maps.tsv`, the game's own map titles in English and German, from the data the
//! COH Stats project extracts from the game (https://github.com/cohstats/coh3-data, MIT).
//! Run with `cargo run --example update_maps` after a patch added maps; the result is checked in.

use std::fmt::Write as _;
use std::fs;
use std::path::Path;

use anyhow::{Context, Result};
use serde_json::Value;

const REPO: &str = "cohstats/coh3-data";

/// `(4) El Alamein` -> `El Alamein`, with the few characters the display's Latin-1 font
/// lacks replaced by their plain relatives.
fn clean(title: &str) -> String {
    let title = title.trim();
    let title = match title.strip_prefix('(').and_then(|rest| rest.split_once(") ")) {
        Some((count, name)) if !count.is_empty() && count.bytes().all(|b| b.is_ascii_digit()) => name,
        _ => title,
    };
    title
        .chars()
        .map(|c| match c {
            '–' | '—' => '-',
            '‘' | '’' => '\'',
            '“' | '”' | '„' => '"',
            '\t' => ' ',
            other => other,
        })
        .collect()
}

#[tokio::main]
async fn main() -> Result<()> {
    let client = reqwest::Client::builder().user_agent("coh3-display update_maps").build()?;
    let get = async |url: String| -> Result<Value> {
        let response = client.get(&url).send().await?.error_for_status().with_context(|| url.clone())?;
        Ok(response.json().await?)
    };

    let tags = get(format!("https://api.github.com/repos/{REPO}/tags?per_page=1")).await?;
    let tag = tags[0]["name"].as_str().context("the repository has no tags")?.to_string();
    let raw = format!("https://raw.githubusercontent.com/{REPO}/{tag}/data");
    let maps = get(format!("{raw}/mp-maps.json")).await?;
    let german = get(format!("{raw}/locales/de-locstring.json")).await?;

    let mut rows = Vec::new();
    for (id, map) in maps.as_object().context("mp-maps.json is not an object")? {
        let name = &map["name"];
        let Some(english) = name["en"].as_str().filter(|english| *english != id.as_str()) else {
            // The file's own header, and scenarios that have no title in the game.
            continue;
        };
        let german = name["locstring"].as_str().and_then(|key| german[key].as_str()).unwrap_or("");
        rows.push((id.as_str(), clean(english), clean(german)));
    }
    rows.sort();

    let mut table = format!(
        "# Map titles as the game shows them: scenario, English, German (empty: use English).\n\
         # Generated by `cargo run --example update_maps` from https://github.com/{REPO}\n\
         # ({tag}, MIT licence, Copyright (c) 2023 COH Stats). Do not edit by hand.\n"
    );
    for (id, english, german) in &rows {
        let _ = writeln!(table, "{id}\t{english}\t{german}");
    }

    let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("src").join("maps.tsv");
    fs::write(&path, table)?;
    println!("wrote {} maps from {tag} to {}", rows.len(), path.display());
    Ok(())
}
